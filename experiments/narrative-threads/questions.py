"""Phase 2: draft questions, reference answers and their evidence, written by Haiku.

The owner's rule: questions are generated by an LLM and validated by an independent human,
then frozen before any strategy runs. The model that builds threads (Sonnet) never writes
them. This script only writes drafts (`results/questions/draft/<doc>.json`); a human review
turns a draft into `results/questions/frozen/<doc>.json`, and nothing here writes there.

Evidence is asked for as verbatim quotes and located deterministically: a quote is kept
with its byte range `[start, end)` only when its exact bytes occur in the document; one
that does not is counted as rejected, never repaired. A question left with no located
evidence is kept in the draft, marked, for the reviewer to drop or fix.

Calls are `claude -p --model haiku`, charged to the ledger's `eval` phase (the USD 3
bucket); a run stops when the ledger refuses a call. Long documents are read in windows on
block boundaries, each asked for its share of the 30 questions.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import subprocess
import sys
from pathlib import Path

from ledger import CapReached, Ledger
from segment import segment

HERE = Path(__file__).resolve().parent
CORPUS = HERE / "corpus"
DRAFTS = HERE / "results" / "questions" / "draft"
ALIAS = "haiku"
PER_DOC = 30
WINDOW_BYTES = 300_000
PROMPT_VERSION = "q1"

TYPES = ["trajectory", "contrast", "causal", "evolution", "local"]

SCHEMA = {
    "type": "object",
    "properties": {"questions": {"type": "array", "items": {
        "type": "object",
        "properties": {
            "question": {"type": "string"},
            "type": {"type": "string", "enum": TYPES},
            "reference_answer": {"type": "string"},
            "evidence": {"type": "array", "items": {"type": "string"}, "minItems": 1},
        },
        "required": ["question", "type", "reference_answer", "evidence"]}}},
    "required": ["questions"],
}

INSTRUCTIONS = """You write evaluation questions for a retrieval experiment over the document below.
Write exactly {n} questions answerable from this text alone. Mix the types:
- trajectory: how an idea, problem or character develops across distant parts of the text (most questions);
- contrast: where the text contradicts, revises or compares positions;
- causal: why something happens, when cause and effect are far apart;
- evolution: how a proposal or decision changed from its first mention to its conclusion;
- local: a single fact stated in one place (at most {local} of them).
For each question give a reference answer (2-4 sentences) and the evidence: the exact passages that
justify it, copied VERBATIM character for character from the document (each 1-3 sentences, no
ellipses, no paraphrase). Trajectory, contrast, causal and evolution questions need evidence from at
least two places far apart. Answer only with the JSON object.

DOCUMENT:
"""


def windows(data: bytes, size: int = WINDOW_BYTES) -> list[tuple[int, int]]:
    """Byte ranges on block boundaries, each at most `size` (a single larger block stands alone)."""
    out, start, end = [], None, None
    for b in segment(data):
        if start is None:
            start = b.start
        elif b.end - start > size:
            out.append((start, end))
            start = b.start
        end = b.end
    if start is not None:
        out.append((start, end))
    return out


def shares(total: int, parts: int) -> list[int]:
    return [total // parts + (1 if i < total % parts else 0) for i in range(parts)]


def locate(data: bytes, lo: int, hi: int, quote: str) -> tuple[int, int] | None:
    """The quote's exact byte range inside [lo, hi), else in the document, else None."""
    q = quote.strip().encode("utf-8")
    if not q:
        return None
    i = data.find(q, lo, hi)
    if i < 0:
        i = data.find(q)
    return (i, i + len(q)) if i >= 0 else None


def ask(prompt: str) -> dict:
    argv = ["claude", "-p", "--model", ALIAS, "--output-format", "json", "--tools", "",
            "--strict-mcp-config", "--json-schema", json.dumps(SCHEMA)]
    out = subprocess.run(argv, input=prompt, capture_output=True, text=True, timeout=900)
    return json.loads(out.stdout)


def answer_of(result: dict) -> dict:
    so = result.get("structured_output")
    if isinstance(so, dict):
        return so
    text = (result.get("result") or "").strip()
    if text.startswith("```"):
        text = text.split("\n", 1)[1].rsplit("```", 1)[0]
    return json.loads(text)


def run_doc(name: str, ledger: Ledger, pinned: dict) -> dict:
    data = (CORPUS / name).read_bytes()
    wins = windows(data)
    counts = shares(PER_DOC, len(wins))
    out_path = DRAFTS / f"{Path(name).stem}.json"
    draft = json.loads(out_path.read_text()) if out_path.exists() else {
        "document": name, "sha256": hashlib.sha256(data).hexdigest(), "status": "draft: pending human review",
        "prompt_version": PROMPT_VERSION, "alias": ALIAS, "windows": [], "questions": [],
        "rejected_quotes": 0}
    done = {w["index"] for w in draft["windows"]}
    for i, ((lo, hi), n) in enumerate(zip(wins, counts)):
        if i in done:
            continue
        ledger.authorize("eval")
        prompt = INSTRUCTIONS.format(n=n, local=max(1, n // 6)) + data[lo:hi].decode("utf-8")
        result = ask(prompt)
        call_id = f"questions:{PROMPT_VERSION}:{name}:w{i}"
        entry = ledger.record("eval", name, ALIAS, result, call_id)
        ids = entry["model_ids"]
        if pinned.setdefault("ids", ids) != ids:
            raise SystemExit(f"model changed mid-experiment: {pinned['ids']} -> {ids}; stopping")
        if result.get("is_error"):
            raise SystemExit(f"{name} w{i}: the CLI reported an error")
        for q in answer_of(result).get("questions", []):
            ev, rejected = [], 0
            for quote in q.get("evidence", []):
                span = locate(data, lo, hi, quote)
                if span:
                    ev.append({"start": span[0], "end": span[1]})
                else:
                    rejected += 1
            draft["rejected_quotes"] += rejected
            draft["questions"].append({
                "id": f"{Path(name).stem[0]}{len(draft['questions']) + 1:02d}", "window": i,
                "type": q.get("type"), "question": q.get("question"),
                "reference_answer": q.get("reference_answer"), "evidence": ev,
                "evidence_rejected": rejected, "needs_review": not ev})
        draft["windows"].append({"index": i, "start": lo, "end": hi, "asked": n, "call_id": call_id,
                                 "model_ids": ids, "charged_usd": entry["charged_usd"]})
        draft["model_ids"] = ids
        out_path.parent.mkdir(parents=True, exist_ok=True)
        out_path.write_text(json.dumps(draft, indent=1, ensure_ascii=False) + "\n")
        print(f"{name} w{i}: {n} asked, {len(draft['questions'])} kept so far, "
              f"USD {entry['charged_usd']:.4f}, eval spent {ledger.spent('eval'):.4f}", file=sys.stderr)
    return draft


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("docs", nargs="*")
    args = ap.parse_args()
    manifest = json.loads((CORPUS / "MANIFEST.json").read_text())
    names = args.docs or [d["file"] for d in manifest["documents"]]
    ledger, pinned = Ledger(), {}
    for name in names:
        try:
            run_doc(name, ledger, pinned)
        except CapReached as e:
            print(f"stopped: {e}; partial drafts kept", file=sys.stderr)
            return 2
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
